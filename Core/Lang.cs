        private static Dictionary<string, string> Build(string code)
        {
            string[] v;
            switch (code)
            {
                case "en": v = EN; break;
                case "fr": v = FR; break;
                case "de": v = DE; break;
                case "pt": v = PT; break;
                case "it": v = IT; break;
                case "ru": v = RU; break;
                case "zh": v = ZH; break;
                case "ja": v = JA; break;
                case "pl": v = PL; break;
                case "tr": v = TR; break;
                case "ko": v = KO; break;
                case "nl": v = NL; break;
                case "uk": v = UK; break;
                case "zht": v = ZHT; break;
                default: return null;
            }

            var d = new Dictionary<string, string>();
            for (int i = 0; i < Keys.Length && i < v.Length; i++)
            {
                d[Keys[i]] = v[i];
            }

            return d;
        }

